def esc(s: str) -> str:
    s = escape(s).replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s


def write(path: str, lang: int):
    keys = set()
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/strings.py. Edit the table there, not this file. -->", "<resources>"]
    for key, en, ar in S:
        assert key not in keys, key
        keys.add(key)
        text = en if lang == 0 else ar
        lines.append(f'    <string name="{key}">{esc(text)}</string>')
    for key, en, ar in P:
        forms = en if lang == 0 else ar
        lines.append(f'    <plurals name="{key}">')
        for q, t in forms.items():
            lines.append(f'        <item quantity="{q}">{esc(t)}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")


